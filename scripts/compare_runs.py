"""Compare training regimes on the same evaluation pipeline.

Reads results/eval_<tag>.json (accuracy, scripts/eval_checkpoints.py) and
results/oracle_<tag>.json (explanations, scripts/oracle_eval.py) written by
scripts/run_eval_sweep.sh for each regime, and writes results/comparison.md.

Regimes (tag = first run name passed to run_eval_sweep.sh):
  original  trained on edge_medium (6-10 nodes)            runs ladder_* / features_edge_medium
  mixed     + 11-16-node graphs + hard families            runs mixed_*
  maskaug   mixed + oracle-labeled masked subgraphs        runs maskaug_*

Usage: python scripts/compare_runs.py
"""

from __future__ import annotations

import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
REGIMES = {
    "original": ("features_edge_medium", lambda m: "features_edge_medium" if m == "features" else f"ladder_{m}_medium"),
    "mixed": ("mixed_features", lambda m: f"mixed_{m}"),
    "maskaug": ("maskaug_features", lambda m: f"maskaug_{m}"),
}
MODELS = ["features", "gcn", "mpnn", "gin", "dsgin"]
ACC_SETS = [("edge_medium", "medium test"), ("hard_eval:decoy", "decoy"), ("hard_eval:multi", "multi"),
            ("hard_eval:symmetric", "symmetric"), ("chain_matched_eval", "chains (unseen)"),
            ("henneberg_large_eval", "14-16 nodes")]
EXP_SETS = [("_chain_matched_eval", "chains"), ("_hard_eval:decoy", "decoy"),
            ("_hard_eval:multi", "multi"), ("_hard_eval:symmetric", "symmetric")]


def mean(vals, scale=1.0, digits=2):
    vals = [v for v in vals if v == v]
    if not vals:
        return "–"
    s = f"{scale * st.mean(vals):.{digits}f}"
    return s + (f" ± {scale * st.pstdev(vals):.{digits}f}" if len(vals) > 1 else "")


def main() -> None:
    acc = {r: json.loads((RES / f"eval_{tag}.json").read_text()) for r, (tag, _) in REGIMES.items()}
    exp = {r: json.loads((RES / f"oracle_{tag}.json").read_text()) for r, (tag, _) in REGIMES.items()}
    out = ["# Training regimes compared (same evaluation pipeline)\n",
           "original = edge_medium only; mixed = + larger graphs + hard families; "
           "maskaug = mixed + oracle-labeled masked subgraphs. original has 3 seeds, the others 5. "
           "Generated by `scripts/compare_runs.py`.\n"]

    out.append("## Accuracy\n")
    out.append("| model | regime | " + " | ".join(name for _, name in ACC_SETS) + " |")
    out.append("|---|---|" + "---|" * len(ACC_SETS))
    for m in MODELS:
        for r, (_, run_of) in REGIMES.items():
            cells = [mean([x["acc"] for x in acc[r].get(f"{run_of(m)}/{s}", [])]) for s, _ in ACC_SETS]
            out.append(f"| {m} | {r} | " + " | ".join(cells) + " |")

    def block(title, note, method, variant, field, scale=1.0, digits=2):
        out.append(f"\n## {title}\n")
        out.append(note + "\n")
        out.append("| model | regime | " + " | ".join(name for _, name in EXP_SETS) + " |")
        out.append("|---|---|" + "---|" * len(EXP_SETS))
        for m in MODELS[1:]:
            for r, (_, run_of) in REGIMES.items():
                cells = [mean([x[field] for x in exp[r].get(f"{ds}|{run_of(m)}|{method}|{variant}", [])], scale, digits)
                         for ds, _ in EXP_SETS]
                out.append(f"| {m} | {r} | " + " | ".join(cells) + " |")

    block("Does the model accept the true certificate? (oracle explanation, F∧V %)",
          "Over examples the model predicts redundant: % where the model keeps its prediction given ONLY a "
          "true minimal certificate. 100 = the certificate is sufficient for the model.",
          "oracle", "raw", "FV", 1.0, 1)
    block("Faithful but invalid (random edge subsets, F∧¬V %)",
          "% of random half-size edge subsets on which the model keeps a 'redundant' prediction although "
          "the subset proves nothing (lower = model is not fooled by non-certificates).",
          "random", "raw", "F_notV", 1.0, 1)
    for method in ("EdgeGrad", "PGExplainer", "GNNExplainer"):
        block(f"{method}: slack score (raw ranking)",
              "1 = the ranking reaches a minimal valid certificate first; 0 = needs every edge "
              "(truly redundant examples).", method, "raw", "slack")
    block("EdgeGrad + certificate step (cert_faith), F∧V %",
          "Ranking -> minimal valid certificate -> most model-faithful alternative.",
          "EdgeGrad", "cert_faith", "FV", 1.0, 1)

    text = "\n".join(out) + "\n"
    (RES / "comparison.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
